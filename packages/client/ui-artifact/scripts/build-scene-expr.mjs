/** Bundle the shared safe expression parser into an inlinable IIFE for exported animations. */
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageDir = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(packageDir, '../../../..')
const entry = join(repoRoot, 'packages/util/values/src/index.ts')
const outDir = join(packageDir, '../src/client')
mkdirSync(outDir, { recursive: true })

execFileSync('cmd.exe', [
  '/c',
  join(repoRoot, 'node_modules/.bin/esbuild.CMD'),
  entry,
  '--bundle',
  '--format=iife',
  '--global-name=SceneExpr',
  '--platform=browser',
  '--target=es2020',
  `--outfile=${join(outDir, 'scene-expr.generated.js')}`,
], { stdio: 'inherit' })

const bundle = readFileSync(join(outDir, 'scene-expr.generated.js'), 'utf8')
writeFileSync(
  join(outDir, 'scene-expr.generated.ts'),
  `/** Generated by scripts/build-scene-expr.mjs; do not edit. */\nexport const sceneExprBundle = ${JSON.stringify(bundle)}\n`,
  'utf8',
)
