/** Generate the framework-free programs embedded in exported SceneSpec animations. */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import { buildSync, context, type BuildOptions, type BuildResult, type BuildContext } from 'esbuild'

type SceneBundleKind = 'expression' | 'renderers'
const KINDS: readonly SceneBundleKind[] = ['expression', 'renderers']

function bundleOptions(root: string, kind: SceneBundleKind): BuildOptions {
  return {
    absWorkingDir: root,
    entryPoints: [join(root, kind === 'expression'
      ? 'packages/util/values/src/index.ts'
      : 'packages/artifact/artifact/src/scene-renderers.ts')],
    bundle: true, format: 'iife', platform: 'browser', target: 'es2020', write: false,
    globalName: kind === 'expression' ? 'SceneExpr' : 'SceneRenderers',
    outfile: join(root, 'packages/artifact/artifact/src', kind === 'expression'
      ? 'scene-expr.generated.js' : 'scene-renderers.generated.js'),
  }
}

function writeChanged(path: string, contents: string): void {
  if (existsSync(path) && readFileSync(path, 'utf8') === contents) return
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, contents, 'utf8')
}

function bindingOf(kind: SceneBundleKind): string {
  return kind === 'expression' ? 'sceneExprBundle' : 'sceneRenderersBundle'
}

function bindingText(kind: SceneBundleKind, program: string): string {
  return `/** Generated by scripts/generate-scene-bundles.ts; do not edit. */\nexport const ${bindingOf(kind)} = ${JSON.stringify(program)}\n`
}

/**
 * Read one generated pair: the browser program and its TypeScript binding.
 * @param root - Repository or fixture root containing the source entry points.
 * @param kind - Program to bundle.
 * @returns Generated file contents keyed by absolute path.
 */
function builtProgram(root: string, kind: SceneBundleKind): Map<string, string> {
  const options = bundleOptions(root, kind)
  const result = buildSync(options)
  const output = result.outputFiles?.[0]
  if (output === undefined || options.outfile === undefined) throw new Error('Scene bundle generation produced no program')
  return new Map([
    [options.outfile, output.text],
    [options.outfile.replace(/\.js$/u, '.ts'), bindingText(kind, output.text)],
  ])
}

/**
 * Compute the files generation would write, without touching the working tree.
 * @param root - Repository or fixture root containing the source entry points.
 * @param kinds - Programs to compute; the package's individual script wrappers select one.
 * @returns Expected contents keyed by absolute path.
 */
export function expectedSceneBundles(root: string, kinds: readonly SceneBundleKind[] = KINDS): Map<string, string> {
  const expected = new Map<string, string>()
  for (const kind of kinds) for (const [path, contents] of builtProgram(root, kind)) expected.set(path, contents)
  return expected
}

/**
 * Report generated programs that exist but no longer match their bundled source.
 *
 * Generation runs on every artifact build and these files are gitignored, so an absent program means
 * "not built yet" rather than stale. The check catches hand edits and interrupted generations.
 * @param root - Repository or fixture root containing the source entry points.
 * @param kinds - Programs to verify; the package's individual script wrappers select one.
 * @returns Absolute paths that generation would rewrite, in stable order.
 */
export function staleSceneBundles(root: string, kinds: readonly SceneBundleKind[] = KINDS): string[] {
  const stale: string[] = []
  for (const [path, contents] of expectedSceneBundles(root, kinds)) {
    if (!existsSync(path) || readFileSync(path, 'utf8') === contents) continue
    stale.push(path)
  }
  return stale.sort()
}

/**
 * List generated programs that generation has not written yet.
 * @param root - Repository or fixture root containing the source entry points.
 * @param kinds - Programs to inspect.
 * @returns Absolute paths of absent generated files, in stable order.
 */
export function unbuiltSceneBundles(root: string, kinds: readonly SceneBundleKind[] = KINDS): string[] {
  return [...expectedSceneBundles(root, kinds).keys()].filter(path => !existsSync(path)).sort()
}

function publish(result: BuildResult, options: BuildOptions, kind: SceneBundleKind): void {
  const output = result.outputFiles?.[0]
  if (output === undefined || options.outfile === undefined) throw new Error('Scene bundle generation produced no program')
  writeChanged(options.outfile, output.text)
  writeChanged(options.outfile.replace(/\.js$/u, '.ts'), bindingText(kind, output.text))
}

/**
 * Generate the script constants before Artifact TypeScript compilation.
 * @param root - Repository or isolated fixture root containing the source entry points.
 * @param kinds - Programs to generate; the package's individual script wrappers select one.
 */
export function generateSceneBundles(root: string, kinds: readonly SceneBundleKind[] = KINDS): void {
  for (const kind of kinds) {
    const options = bundleOptions(root, kind)
    publish(buildSync(options), options, kind)
  }
}

/** One owned generator lifetime; a rebuild error disposes both watchers and exits unsuccessfully. */
export interface SceneBundleWatcher {
  readonly exited: Promise<number>
  /** Dispose both source watchers and wait for pending generation to finish. */
  dispose(): Promise<void>
}

/**
 * Watch the source dependency graphs, publishing changed constants before downstream rebuilds.
 * @param root - Repository or isolated fixture root containing the source entry points.
 * @returns Watcher after both initial programs are generated; later errors settle exited with one.
 * @throws When an initial program cannot be generated.
 */
export async function watchSceneBundles(root: string): Promise<SceneBundleWatcher> {
  const contexts: BuildContext[] = []
  const exit = Promise.withResolvers<number>()
  let exitCode = 0
  let stopping: Promise<void> | undefined
  const dispose = (): Promise<void> => stopping ??= Promise.all(contexts.map(item => item.dispose()))
    .then(() => { exit.resolve(exitCode) })
  const fail = (error: unknown): void => {
    exitCode = 1
    console.error('Scene bundle generation failed', error)
    void dispose().catch((disposalError: unknown) => {
      console.error('Scene bundle watcher disposal failed', disposalError)
      exit.resolve(1)
    })
  }
  try {
    for (const kind of KINDS) {
      const options = bundleOptions(root, kind)
      const ready = Promise.withResolvers<void>()
      const watcher = await context({
        ...options,
        plugins: [{ name: 'publish-scene-program', setup(build) {
          build.onEnd((result) => {
            try {
              if (result.errors.length > 0) throw new Error(`Cannot generate the ${kind} scene program`)
              publish(result, options, kind)
              ready.resolve()
            } catch (error) {
              ready.reject(error)
              fail(error)
            }
          })
        } }],
      })
      contexts.push(watcher)
      await watcher.watch()
      await ready.promise
    }
    return { exited: exit.promise, dispose }
  } catch (error) {
    await dispose()
    throw error
  }
}

async function main(): Promise<void> {
  const { values } = parseArgs({
    options: { root: { type: 'string' }, watch: { type: 'boolean', default: false }, check: { type: 'boolean', default: false } },
  })
  const root = values.root === undefined ? fileURLToPath(new URL('..', import.meta.url)) : resolve(values.root)
  if (values.check) {
    const stale = staleSceneBundles(root)
    if (stale.length > 0) {
      throw new Error(['generate-scene-bundles: generated programs no longer match their sources:', ...stale,
        'Run `pnpm run generate-scene-bundles` and rebuild; these files are gitignored build output.',
      ].join('\n'))
    }
    console.log(`generate-scene-bundles: every generated program matches its bundled source (${String(unbuiltSceneBundles(root).length)} not built yet).`)
    return
  }
  if (!values.watch) { generateSceneBundles(root); return }
  const watcher = await watchSceneBundles(root)
  const stop = (): void => { void watcher.dispose() }
  process.once('SIGINT', stop)
  process.once('SIGTERM', stop)
  process.exitCode = await watcher.exited
  process.off('SIGINT', stop)
  process.off('SIGTERM', stop)
}

if (import.meta.main) void main().catch((error: unknown) => { console.error(error); process.exitCode = 1 })
